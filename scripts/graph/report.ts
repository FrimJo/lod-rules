import { CATEGORIES, RELATION_CATEGORY, type AnalysedGraph, type Relation } from './types.ts';
import { compare } from './compare.ts';

export const GRAPH_REPORT = 'docs/graph-report.md';

const code = (text: string): string => `\`${text}\``;
const plural = (count: number, noun: string): string => `${count} ${noun}${count === 1 ? '' : 's'}`;

/** A left-aligned markdown table, padded the way Prettier formats it. */
function table(header: string[], rows: string[][]): string[] {
  const widths = header.map((cell, column) =>
    Math.max(3, cell.length, ...rows.map((row) => row[column]?.length ?? 0)),
  );
  const line = (cells: string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(' | ')} |`;
  return [line(header), line(widths.map((width) => '-'.repeat(width))), ...rows.map(line)];
}

/**
 * Renders `docs/graph-report.md`: edge counts by relation and by category, then the anomaly
 * lists (dangling ids, cycles per relation, procedure steps restating a rule, unresolved
 * pointers). Pure and deterministic. It lists anomalies without dispositions.
 */
export function renderGraphReport(graph: AnalysedGraph): string {
  const byRelation = new Map<Relation, number>();
  for (const edge of graph.edges)
    byRelation.set(edge.relation, (byRelation.get(edge.relation) ?? 0) + 1);
  const relations = (Object.keys(RELATION_CATEGORY) as Relation[]).sort(compare);
  const byCategory = CATEGORIES.map(
    (category) =>
      [
        category,
        relations
          .filter((relation) => RELATION_CATEGORY[relation] === category)
          .reduce((sum, relation) => sum + (byRelation.get(relation) ?? 0), 0),
      ] as const,
  );
  const { dangling, cycles, unresolved, stepDuplicates } = graph.anomalies;

  const lines = [
    '# Dependency graph report',
    '',
    '<!-- Generated by `npm run graph -- report` from the canonical corpus via scripts/graph.',
    'Do not edit by hand. -->',
    '',
    'Derived from the canonical corpus by `scripts/graph/`. The anomaly lists below are reported,',
    'not resolved: none carries a disposition.',
    '',
    '## Summary',
    '',
    `${plural(graph.nodes.length, 'node')}, ${plural(graph.edges.length, 'edge')}.`,
    '',
    `- Dangling ids: ${dangling.length}`,
    `- Cycles: ${cycles.reduce((sum, group) => sum + group.cycles.length, 0)} across ${plural(cycles.length, 'relation')}`,
    `- Unresolved pointers: ${unresolved.length}`,
    `- Procedure steps restating an uncited rule: ${stepDuplicates.length}`,
    '',
    '## Edges by category',
    '',
    ...table(
      ['Category', 'Edges'],
      byCategory.map(([category, count]) => [category, String(count)]),
    ),
    '',
    '## Edges by relation',
    '',
    ...table(
      ['Relation', 'Category', 'Edges'],
      relations.map((relation) => [
        code(relation),
        RELATION_CATEGORY[relation],
        String(byRelation.get(relation) ?? 0),
      ]),
    ),
    '',
    '## Dangling ids',
    '',
    ...(dangling.length === 0
      ? ['No dangling ids.']
      : dangling.map(
          ({ source, relation, target, field }) =>
            `- ${code(source)} ${code(relation)} → ${code(target)} (field ${code(field)})`,
        )),
    '',
    '## Cycles per relation',
    '',
    ...(cycles.length === 0
      ? ['No cycles.']
      : cycles.flatMap((group) => [
          `### ${code(group.relation)} (${plural(group.cycles.length, 'cycle')})`,
          '',
          ...group.cycles.map((cycle) => `- ${[...cycle, cycle[0] ?? ''].map(code).join(' → ')}`),
          '',
        ])),
  ];
  if (cycles.length === 0) lines.push('');
  lines.push(
    '## Procedure steps restating an uncited rule',
    '',
    ...(stepDuplicates.length === 0
      ? ['None.']
      : stepDuplicates.map(
          ({ procedure, step, rule, effects }) =>
            `- ${code(`${procedure}#${step}`)} → ${code(rule)} (${effects.map(code).join(', ')})`,
        )),
    '',
    '## Unresolved pointers',
    '',
    ...(unresolved.length === 0
      ? ['No unresolved pointers.']
      : unresolved.map(({ owner, wording }) => `- ${code(owner)}: ${wording}`)),
  );
  return `${lines.join('\n')}\n`;
}
